ae <- read_raw("AE") |>
  mutate(
    STUDYID = "VAXF101",
    DOMAIN = "AE",
    USUBJID = paste0("VAXF101-", SUBJECT),
    AETERM = trimws(AETERM),
    AEDECOD = unname(pt[toupper(AETERM)]),
    AEBODSYS = unname(soc[AEDECOD]),
