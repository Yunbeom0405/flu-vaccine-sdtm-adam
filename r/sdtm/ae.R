    AEENDTC = iso_date(AEENDAT)) |>
  left_join(dm_ref(), by = "USUBJID") |>
  mutate(
    AEENRTPT = if_else(AEONGO == "Y", "ONGOING", NA_character_),
    AEENTPT = if_else(AEONGO == "Y", substr(RFPENDTC, 1, 10), NA_character_),
    EPOCH = epoch(AESTDTC, RFXSTDTC),
    AESTDY = study_day(AESTDTC, RFSTDTC),
    AEENDY = study_day(AEENDTC, RFSTDTC)) |>
  add_seq("AESEQ", c("AEDECOD", "AESTDTC"))

